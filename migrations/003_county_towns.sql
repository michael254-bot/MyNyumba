INSERT INTO areas (county_id, name, slug)
SELECT c.id, n.name, n.slug
FROM new_areas n
JOIN counties c ON c.slug = n.county_slug
WHERE NOT EXISTS (
  SELECT 1 FROM areas a WHERE a.county_id = c.id AND lower(a.name) = lower(n.name)
);

